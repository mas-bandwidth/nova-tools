var update = flag.Bool("update", false, "rewrite testdata/features/ROADMAP.golden.md from what the code renders")

func decodeFeatureFixture(t *testing.T) *Features {
	t.Helper()
	raw, err := os.ReadFile("testdata/features/roadmap.sexp")
	require.NoError(t, err)
	require.True(t, IsFeatureForm("roadmap.sexp", raw))
	fs, err := DecodeFeatures("testdata/features/roadmap.sexp", raw)
	require.NoError(t, err)
	files, err := fs.ApplyEvidenceDir("testdata/features/roadmap-evidence")
	require.NoError(t, err)
	require.Equal(t, 1, files, "a dot file is not applied")
	return fs
}

// The fixture renders testdata/features/ROADMAP.golden.md byte for byte, every
// time. Run go test ./pkg/roadmap -run TestFeaturesGolden -update to rewrite it.
func TestFeaturesGolden(t *testing.T) {
	t.Parallel()
	page := RenderFeatures(decodeFeatureFixture(t), "docs/roadmap.sexp", "docs/roadmap-evidence")
	require.Equal(t, page, RenderFeatures(decodeFeatureFixture(t), "docs/roadmap.sexp", "docs/roadmap-evidence"))
	if *update {
		require.NoError(t, os.WriteFile("testdata/features/ROADMAP.golden.md", []byte(page), 0o644))
	}
	want, err := os.ReadFile("testdata/features/ROADMAP.golden.md")
	require.NoError(t, err)
	require.Equal(t, string(want), page)
}

// The cells follow the one rule: ✅ only when every task under the cell is done,
// the overlay moves a task, a later row says so, and the complete row is the
// floor of the ✅ share per column.
func TestFeaturesCellsAndComplete(t *testing.T) {
	t.Parallel()
	fs := decodeFeatureFixture(t)
	page := RenderFeatures(fs, "docs/roadmap.sexp", "")
	for _, want := range []string{
		"| feature | go | cs |\n|---|:---:|:---:|\n",
		"| integers | ✅ | ✅ |\n",
		"| floats | ✅ | ❌ |\n", // go/f64 moved to done by the overlay; a work-set cell
		"| tagged unions (later) | ❌ | ❌ |\n",
		"| complete | 66% | 33% |\n",
		"| feature | done |\n|---|:---:|\n| render a page | ✅ |\n| check for drift | ❌ |\n| complete | 50% |\n",
		"[Source data](docs/roadmap.sexp)",
		"<!-- Generated from docs/roadmap.sexp by nova-tools tools/roadmap.",
	} {
		require.Contains(t, page, want)
	}
	require.NotContains(t, page, "cs-floats", "extra keys are kept, not rendered")
	rows, done := fs.AreaTotals("wire")
	require.Equal(t, [2]int{3, 1}, [2]int{rows, done}, "a row is done when every column is")
}

