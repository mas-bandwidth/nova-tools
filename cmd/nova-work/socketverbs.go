// verbFamilies are the first words that take a sub-verb, mapped to the
// sub-verbs the spec gives them. A family named with no sub-verb, or with one
// the spec does not spell, is refused naming the ones there are, rather than
// dialling a session with a request line no session can answer.
var verbFamilies = map[string][]string{}

func init() {
	for _, v := range allSocketVerbs() {
		head, sub, ok := strings.Cut(v, " ")
		if !ok {
			continue
		}
		verbFamilies[head] = append(verbFamilies[head], sub)
	}
	for head := range verbFamilies {
		sort.Strings(verbFamilies[head])
	}
}

// allSocketVerbs is every verb the client sends over the socket: the four that
// were already in verbFlags and socketVerbs' own. query is not here: it has a
// verb function of its own because the spec gives it constraints the client
// can check without the session (docs/SPEC-WORK.md, the query verb's own
// parenthetical), and run dispatches it by name.
func allSocketVerbs() []string {
	out := make([]string, 0, len(socketVerbs)+4)
	out = append(out, "session start", "session status", "session stop", "query")
	out = append(out, socketVerbs...)
	sort.Strings(out)
	return out
}

// resolveSocketVerb reads the verb off the front of the command line. A verb
// is one or two words and never more, so the longer spelling is tried first:
// `state` is a mutation verb and `state load` is a different thing entirely,
// and reading one as the other would send a load's flags to the mutation.
func resolveSocketVerb(head string, rest []string) (verb string, args []string, ok bool) {
	if len(rest) > 0 {
		if two := head + " " + rest[0]; verbFlags[two] != nil {
			return two, rest[1:], true
		}
	}
	if verbFlags[head] != nil && head != "query" {
		return head, rest, true
	}
	return "", nil, false
}

