// The socket verbs beyond the four the client carried.
//
// docs/SPEC-WORK.md's verbs block (the fenced block under "The verbs") is the
// list: "Session verbs run the process; every other verb is a client verb
// addressed to a session by `--session <path>` (required; no default)". The
// client reached four of them -- session start, session status, session stop
// and query -- so every other thing the kernel really keeps (nodes, states,
// roadmaps, axes, cells, renders, undo and redo plans, machines, events,
// dependency edges) was real to a Lisp test and to nobody at a shell.
//
// This file is the rest of that block. It adds no behaviour of its own: a
// socket verb IS its flag surface, since the client is thin by the spec's own
// rule -- "The values travel as the caller spelled them and the session
// validates every one" -- so a verb is one row of verbFlags plus its name in
// socketVerbs, and sessionVerb already spells the request line and classifies
// the reply.
//
// EVERY ROW BELOW IS READ OUT OF THE SPEC, NOT WRITTEN BESIDE IT.
// specverbs_test.go parses the same fenced block and fails if the two differ
// in a verb, a flag, an order or a flag's kind, so this table cannot drift
// from the document that defines it and a new flag in the spec is a red test
// rather than a silent gap.
//
// Four of the block's lines are deliberately NOT here, each for a reason the
// test knows by name:
//
//   - `state load` and `savepoint restore` are read-only local processes, not
//     client verbs: they take no --session, start no daemon and take no
//     ownership ("isolated and read-only" on both lines). They belong to a
//     reader this client does not yet carry.
//   - `report` is SPEC-AHEAD (#854) and has no kernel symbol at all; building
//     its client half first would be the spec growing a second time.
//   - `clip` COLLIDES: the spec's `clip --session <path> --as <name>
//     --git-timeout <seconds>` is a long operation on the resident session,
//     and `nova-work clip --worktree <dir> --branch <name> --base <ref>
//     --harvest <dir>` already ships as a local git verb of the swarm. One
//     name, two verbs, and nothing in the spec says which wins. That is a
//     question for the section's owners and not a thing to decide in a table.

